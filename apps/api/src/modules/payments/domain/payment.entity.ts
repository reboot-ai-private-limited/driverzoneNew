/**
 * DOMAIN — one attempt to move money between a customer and the company.
 *
 * A payment is a SEPARATE record from the booking it belongs to, not a status on it. Two reasons,
 * both learned the hard way by everyone who has done it the other way:
 *
 *   1. A booking is paid more than once. The fare at confirmation, then a settlement for waiting
 *      time at completion, then possibly a refund. Those are three movements with three gateway
 *      references and three outcomes, and they will not fit in one field.
 *   2. A gateway is asynchronous and unreliable. The webhook confirming a capture may arrive
 *      before the API's own response, twice, or an hour late. Reconciling that needs a row to
 *      reconcile against.
 */

export const PAYMENT_KINDS = [
  /** The locked quote, collected to confirm the booking. */
  'BOOKING',
  /** Extras accrued during the trip — waiting time — collected at completion. */
  'SETTLEMENT',
  /** Money going back: a cancellation refund, or a booking no driver was found for. */
  'REFUND',
] as const;
export type PaymentKind = (typeof PAYMENT_KINDS)[number];

/**
 * `CREATED` is ours alone — an intent exists but the customer has not been sent to the gateway.
 * `PENDING` means the gateway has it and the outcome is unknown; this is the state a webhook
 * resolves. `CAPTURED` and `FAILED` are terminal for a charge, `REFUNDED` for a refund.
 */
export const PAYMENT_STATUSES = [
  'CREATED',
  'PENDING',
  'CAPTURED',
  'FAILED',
  'REFUNDED',
  'PARTIALLY_REFUNDED',
] as const;
export type PaymentStatus = (typeof PAYMENT_STATUSES)[number];

/**
 * The allowed moves. Same shape as the booking state machine and for the same reason: a payment
 * that goes from `FAILED` back to `CAPTURED` because a late webhook arrived out of order is how
 * a customer gets a free trip.
 */
const TRANSITIONS: Record<PaymentStatus, readonly PaymentStatus[]> = {
  CREATED: ['PENDING', 'FAILED'],
  PENDING: ['CAPTURED', 'FAILED'],
  CAPTURED: ['REFUNDED', 'PARTIALLY_REFUNDED'],
  PARTIALLY_REFUNDED: ['REFUNDED', 'PARTIALLY_REFUNDED'],
  /*
   * ONE exit, and only this one. Razorpay documents that a UPI retry can send `payment.failed`
   * followed by `payment.captured` for a single transaction — so a failed payment that later
   * captures is a real, expected sequence, not a resurrection. Without it the customer is debited
   * and the booking still expires.
   */
  FAILED: ['CAPTURED'],
  REFUNDED: [],
};

export function canTransition(from: PaymentStatus, to: PaymentStatus): boolean {
  return TRANSITIONS[from].includes(to);
}

/** A payment that has actually collected money, and can therefore be refunded. */
export function isCaptured(status: PaymentStatus): boolean {
  return status === 'CAPTURED' || status === 'PARTIALLY_REFUNDED';
}

export interface Payment {
  id: string;
  bookingId: string;
  customerId: string;
  kind: PaymentKind;
  status: PaymentStatus;
  amountPaise: number;
  /** How much of `amountPaise` has gone back. Always 0 for a REFUND row itself. */
  refundedPaise: number;
  /**
   * The gateway's id for the thing we CREATED — for Razorpay the ORDER (`order_…`). Null until an
   * intent exists. Webhooks are matched back to this row by it.
   */
  gatewayRef: string | null;
  /**
   * The gateway's id for the PAYMENT itself (`pay_…`), which only exists once a customer has paid,
   * so it arrives with the webhook and never at creation.
   *
   * Stored separately because Razorpay refunds are `POST /v1/payments/:id/refund` — against the
   * payment, not the order. Refunding with the order id hits the wrong endpoint entirely, and
   * nothing would reveal that until money had to go back.
   */
  providerPaymentId: string | null;
  /**
   * The caller's idempotency key, unique-indexed.
   *
   * This is what makes a double-tapped Confirm button charge once. It is generated by the client
   * per user intent — one tap, one key, however many network retries it takes — and the server
   * returns the original payment rather than creating a second.
   */
  idempotencyKey: string;
  /** Customer-safe text when the gateway declined. Null otherwise. */
  failureReason: string | null;
  createdAt: Date;
  updatedAt: Date;
}
