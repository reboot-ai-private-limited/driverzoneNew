const { withAndroidManifest } = require('expo/config-plugins');

/**
 * Lets the ringing offer take over a LOCKED screen.
 *
 * `offerNotification.ts` asks Android for a `fullScreenAction`, which is the same mechanism an
 * incoming phone call uses. Android honours it by launching `MainActivity` — but on a locked
 * device that activity comes up BEHIND the keyguard unless it declares otherwise. The driver
 * then hears the tone and sees a banner, and has to unlock before the offer appears, which is
 * precisely the delay a 45-second offer cannot afford.
 *
 * `showWhenLocked` puts the activity in front of the keyguard; `turnScreenOn` wakes the display
 * so there is something to see. Both are activity attributes, so neither can be expressed in
 * `app.json` — and `android/` is regenerated by every prebuild, so editing the manifest by hand
 * would vanish on the next one.
 *
 * The driver still unlocks before anything sensitive: accepting a trip navigates on, and Android
 * requires dismissing the keyguard to reach the rest of the app.
 */
module.exports = function withRingOverLockScreen(config) {
  return withAndroidManifest(config, (cfg) => {
    const application = cfg.modResults.manifest.application?.[0];
    const activity = application?.activity?.find(
      (candidate) => candidate.$?.['android:name'] === '.MainActivity',
    );

    // Prebuild owns MainActivity's declaration; if Expo ever renames it, failing loudly here is
    // better than shipping a build whose ring silently stays behind the lock screen.
    if (activity === undefined) {
      throw new Error(
        'withRingOverLockScreen: .MainActivity not found in AndroidManifest.xml — the ring cannot show over the lock screen.',
      );
    }

    activity.$['android:showWhenLocked'] = 'true';
    activity.$['android:turnScreenOn'] = 'true';

    return cfg;
  });
};
