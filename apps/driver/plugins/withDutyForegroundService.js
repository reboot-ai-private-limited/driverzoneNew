const { withAndroidManifest } = require('expo/config-plugins');

/**
 * Declares Notifee's foreground service as a LOCATION service.
 *
 * Android 14 (API 34) made `foregroundServiceType` mandatory: `startForeground()` throws
 * `MissingForegroundServiceTypeException` unless the service declares a type in the manifest and
 * the app holds the matching runtime permission. Notifee ships `app.notifee.core.ForegroundService`
 * in its own AAR manifest WITHOUT a type — it cannot know what any given app uses it for — so the
 * attribute has to be merged in here.
 *
 * `tools:replace` is the load-bearing part. Without it the manifest merger sees two declarations
 * of the same service and fails the build; with it, ours wins.
 *
 * Why a plugin and not `app.json`: this is a `<service>` attribute, which the Expo config schema
 * has no field for, and `android/` is regenerated by every prebuild so hand-editing the manifest
 * would vanish on the next one. Same reasoning as `withRingOverLockScreen.js` beside it.
 *
 * The paired runtime permissions (`FOREGROUND_SERVICE`, `FOREGROUND_SERVICE_LOCATION`,
 * `ACCESS_BACKGROUND_LOCATION`) live in `app.json`, where the schema does have a field.
 *
 * See docs/LLD/driver-app.md S-8 and `src/duty/dutyForegroundService.ts`.
 */
const SERVICE_NAME = 'app.notifee.core.ForegroundService';

module.exports = function withDutyForegroundService(config) {
  return withAndroidManifest(config, (cfg) => {
    const manifest = cfg.modResults.manifest;

    // `tools:` is not declared on a stock Expo manifest, and `tools:replace` below is inert
    // without it — silently, which would show up only as the Android 14 crash it prevents.
    manifest.$ = manifest.$ ?? {};
    manifest.$['xmlns:tools'] = 'http://schemas.android.com/tools';

    const application = manifest.application?.[0];
    if (application === undefined) {
      throw new Error(
        'withDutyForegroundService: no <application> in AndroidManifest.xml — cannot declare the duty foreground service.',
      );
    }

    application.service = application.service ?? [];

    const existing = application.service.find(
      (candidate) => candidate.$?.['android:name'] === SERVICE_NAME,
    );

    const attributes = {
      'android:name': SERVICE_NAME,
      'android:foregroundServiceType': 'location',
      'tools:replace': 'android:foregroundServiceType',
    };

    if (existing === undefined) {
      application.service.push({ $: attributes });
    } else {
      existing.$ = { ...existing.$, ...attributes };
    }

    return cfg;
  });
};
